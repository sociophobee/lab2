# Початковий список
my_list = [10, 20, 30, 40, 50, 60]
print("Початковий список:", my_list)

# Нові елементи, які треба вставити
elements_to_insert = [99, 88, 77]

# Починаємо вставку з індексу 1 (друга позиція)
index = 1

for item in elements_to_insert:
    # Перевіряємо, щоб не вийти за межі списку
    if index <= len(my_list):
        my_list.insert(index, item)
        # Збільшуємо індекс на 2, щоб перейти до наступної парної позиції
        index += 2

print("Список після вставки:", my_list)